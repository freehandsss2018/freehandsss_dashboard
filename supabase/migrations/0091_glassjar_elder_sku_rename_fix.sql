-- 更正 0090：大寶價階套用條件搞錯 + SKU 命名有歧義（2026-08-22，D65續IV-follow 更正）
--
-- ❌ 0090 的錯誤：把新價 $1,680/$1,980 綁在「零嬰兒 + 有大寶 + 無父母」（純大寶單），
--    並命名為「玻璃瓶套裝 (大寶2肢/大寶4肢)」。
--
-- ✅ Fat Mo 2026-08-22 澄清的業務定義（此前從未成文，為本次錯誤根因）：
--      嬰兒 = 初生或客人的「首個」孩子
--      大寶 = 客人的「第二個」孩子，即嬰兒的哥哥/姐姐
--    「大寶」是相對於「嬰兒」而存在的稱謂 → **純大寶單在定義上不可能**：
--    若訂單中沒有嬰兒，那個被倒模的孩子本身就會被定義為「嬰兒」。
--    故 0090 綁定的那一格永遠不會觸發，等於新價從未生效。
--
-- ✅ 正確條件：大寶「有參與」（不論幾多肢）且無父母 → 該件用 +$300 價階。
--    因大寶必然與嬰兒並存，此格即「嬰兒 + 大寶、無父母」。
--    2肢 $1,680（純嬰兒同 tier $1,380）／4肢 $1,980（純嬰兒同 tier $1,680）。
--    含父母一律 $2,580 flat（migration 0060）不受影響；純嬰兒價不變。
--
-- ⚠️ 連帶推翻 2026-07-21 定案：肢數 tier 自本次起**只數嬰兒肢體**
--    （原定「大寶肢體同嬰兒肢體同等地位一齊計總數」）。大寶改為以「有冇參與」
--    做 +$300 修正項，不再影響 2肢/4肢 分級。前端 _pDeriveSkuName() 已同步。
--
-- SKU 改名：「(大寶N肢)」→「(N肢+大寶)」。原名有歧義（易誤讀為「大寶有 N 肢」），
-- 新名 tier 在前、修正項在後，語義為「N肢 tier，且有大寶參與」。
--
-- 安全性：0090 的兩個 SKU 建立後零訂單引用（已查 order_items = 0 筆），故直接 DELETE。
-- 冪等：DELETE 用 IN、INSERT 用 ON CONFLICT DO NOTHING，重複執行安全。

